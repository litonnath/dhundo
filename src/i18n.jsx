// ===========================================================================
// i18n.jsx -- English, Hindi, Bengali, and nine more loaded on demand.
//
// WHY BENGALI IS NOT AN AFTERTHOUGHT HERE
// Most of the people this directory is for read Bengali more comfortably than
// English, and several will not read English at all. A service that lists
// রাজমিস্ত্রি but labels every button in English is only half usable.
//
// The category names already come from the database in both languages
// (trades.name_en / name_bn); this covers the interface around them.
//
// HOW IT WORKS
// One dictionary, one hook, the choice kept in localStorage. No library --
// an i18n package would be larger than every string in this file combined.
//
// A NOTE ON THE TRANSLATIONS
// These are written to be plain and spoken, not formal. Where a word is
// normally said in English even by Bengali speakers here ("সাইন ইন"), it is
// left transliterated rather than forced into a formal Bengali equivalent
// nobody uses out loud. They are worth a read-through by a native speaker
// before launch -- correcting a phrase is a one-line change in this file.
// ===========================================================================
